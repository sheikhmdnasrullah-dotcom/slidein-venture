/**
 * Builds the whole SlideIn logo system from ONE source: slidein-symbol-master.svg geometry (logo-engine.mjs
 * SYMBOL) + the outlined Fraunces wordmark (wordmark/wordmark.json). Nothing is drawn by hand twice.
 *
 *   SVGO_DIR=<dir with node_modules/svgo> node source/build_logos.mjs
 *
 * Writes:  source/*-master.svg (grouped, unoptimised)   logo/<layout>/*.svg (optimised, all colourways)
 *          exports/web|social|print|presentation|application   source/logo-metrics.json
 */
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { lockup, toSvg, COLORWAYS, SYMBOL, IVORY, INK } from './logo-engine.mjs';
import svgoConfig from './svgo.config.mjs';
import { chromium } from '/Users/nasrullahtanim/Downloads/01-Projects/SlideinVenture/marketing-site/node_modules/playwright/index.mjs';
const root = new URL('../', import.meta.url).pathname;
const req = createRequire('/Users/nasrullahtanim/Downloads/01-Projects/SlideinVenture/marketing-site/package.json');
const sharp = req('sharp');
const { optimize } = createRequire(`${process.env.SVGO_DIR}/`)('svgo');

const STOP = 96 / SYMBOL.box;            // the stop square as a fraction of the symbol's height: the system's unit "x"
const GAP = +(1.25 * STOP).toFixed(4);   // symbol-to-wordmark gap = 1.25x
const LAYOUTS = {
  primary:  { dir: 'primary',  name: 'slidein-logo-horizontal', title: 'SlideIn', opts: { layout: 'horizontal', cut: 'display', tracking: -0.02, k: 1.0, gap: GAP } },
  compact:  { dir: 'compact',  name: 'slidein-logo-compact',    title: 'SlideIn', opts: { layout: 'horizontal', cut: 'text',    tracking: -0.01, k: 1.0, gap: GAP } },
  stacked:  { dir: 'stacked',  name: 'slidein-logo-stacked',    title: 'SlideIn', opts: { layout: 'stacked',    cut: 'display', tracking: -0.02, k: 2.8, stackGap: 0.24 } },
  symbol:   { dir: 'symbol',   name: 'slidein-symbol',          title: 'SlideIn symbol', opts: { symbolOnly: true } },
  wordmark: { dir: 'wordmark', name: 'slidein-wordmark',        title: 'SlideIn', opts: { wordOnly: true, cut: 'display', tracking: -0.02 } },
};
const WAYS = { color: '', reversed: '-reversed', black: '-black', white: '-white', orange: '-orange', gray: '-gray' };
const w = (path, data) => { mkdirSync(path.replace(/\/[^/]*$/, ''), { recursive: true }); writeFileSync(path, data); };
const metrics = {};

// ── 1. masters (grouped, unoptimised) + production SVGs (optimised) ───────────────────────────────────
const svgs = {};   // key `${layout}/${way}` -> optimised svg string
for (const [lid, L] of Object.entries(LAYOUTS)) {
  for (const [way, suffix] of Object.entries(WAYS)) {
    const lk = lockup({ ...L.opts, colors: COLORWAYS[way] });
    const raw = toSvg(lk, { title: L.title });
    const opt = optimize(raw, { ...svgoConfig, path: lid }).data + '\n';
    svgs[`${lid}/${way}`] = opt; w(`${root}logo/${L.dir}/${L.name}${suffix}.svg`, opt);
    if (way === 'color') metrics[lid] = { width: lk.w, height: lk.h, symbolHeight: +lk.meta.Hs.toFixed(2), stopSide: +lk.meta.stopSide.toFixed(2), aspect: +(lk.w / lk.h).toFixed(4), bytes: opt.length, rawBytes: raw.length };
  }
}
const master = (file, lid, comment) => w(root + 'source/' + file, toSvg(lockup({ ...LAYOUTS[lid].opts, colors: COLORWAYS.color }), { title: 'SlideIn', groups: true, comment }));
master('slidein-logo-horizontal-master.svg', 'primary', 'SlideIn primary lockup. Symbol: slidein-symbol-master.svg geometry, height = wordmark ascender; gap = 1.25x (x = stop square). Wordmark: Fraunces 600, opsz 48, tracking -0.02em, outlined (SIL OFL 1.1; see source/wordmark/). Generated by source/build_logos.mjs: edit the engine, not this file.');
master('slidein-logo-stacked-master.svg', 'stacked', 'SlideIn stacked lockup. Generated by source/build_logos.mjs.');
master('slidein-wordmark-master.svg', 'wordmark', 'SlideIn wordmark. Fraunces 600, opsz 48, tracking -0.02em, outlined glyphs; live-type source: source/wordmark/extract_wordmark.mjs + OFL.txt. Generated by source/build_logos.mjs.');

// ── 2. raster helpers ──────────────────────────────────────────────────────────────────────────────
const dims = svg => { const m = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/); return [+m[1], +m[2]]; };
async function png(svg, width, file, { webp = false } = {}) {
  const [sw] = dims(svg), density = Math.min(2400, Math.max(72, 72 * width / sw * 1.0));
  let img = sharp(Buffer.from(svg), { density }).resize({ width }).ensureAlpha();
  img = webp ? img.webp({ quality: 92, alphaQuality: 100, effort: 6 }) : img.png({ compressionLevel: 9 });
  w(file, await img.toBuffer());
}
const E = d => root + 'exports/' + d;

// ── 3. exports ─────────────────────────────────────────────────────────────────────────────────────
for (const px of [320, 640, 1280, 1920]) await png(svgs['primary/color'], px, E(`web/slidein-logo-horizontal-${px}w.png`));
for (const way of ['reversed', 'black', 'white']) for (const px of [640, 1280]) await png(svgs[`primary/${way}`], px, E(`web/slidein-logo-horizontal-${way}-${px}w.png`));
for (const px of [320, 640]) await png(svgs['compact/color'], px, E(`web/slidein-logo-compact-${px}w.png`));
for (const px of [640, 1280]) await png(svgs['stacked/color'], px, E(`web/slidein-logo-stacked-${px}w.png`));
for (const px of [320, 640, 1280]) await png(svgs['wordmark/color'], px, E(`web/slidein-wordmark-${px}w.png`));
for (const px of [64, 128, 256, 512, 1024]) await png(svgs['symbol/color'], px, E(`web/slidein-symbol-${px}.png`));
for (const way of ['black', 'white', 'orange']) await png(svgs[`symbol/${way}`], 512, E(`web/slidein-symbol-${way}-512.png`));
// presentation: optimised WebP for slides and digital decks
await png(svgs['primary/color'], 1920, E('presentation/slidein-logo-horizontal-1920w.webp'), { webp: true });
await png(svgs['primary/reversed'], 1920, E('presentation/slidein-logo-horizontal-reversed-1920w.webp'), { webp: true });
await png(svgs['stacked/color'], 1280, E('presentation/slidein-logo-stacked-1280w.webp'), { webp: true });

// composites on a solid ground (avatars, application icons, social card): the symbol / logo is placed from the vector
async function onGround(svg, { size, bg, frac, file, w: cw, h: ch }) {
  const W = cw ?? size, H = ch ?? size, [sw, sh] = dims(svg);
  const target = Math.round(W * frac), s = target / sw;
  const art = await sharp(Buffer.from(svg), { density: Math.min(2400, 72 * s) }).resize({ width: target }).png().toBuffer();
  const meta = await sharp(art).metadata();
  w(file, await sharp({ create: { width: W, height: H, channels: 4, background: bg } })
    .composite([{ input: art, left: Math.round((W - meta.width) / 2), top: Math.round((H - meta.height) / 2) }]).png({ compressionLevel: 9 }).toBuffer());
}
const IV = { r: 0xF6, g: 0xF4, b: 0xF0, alpha: 1 }, BK = { r: 0x0A, g: 0x0A, b: 0x0A, alpha: 1 };
await onGround(svgs['symbol/color'], { size: 1024, bg: IV, frac: 0.56, file: E('social/slidein-avatar-1024.png') });          // 56%: survives a circular crop
await onGround(svgs['symbol/color'], { size: 500, bg: IV, frac: 0.56, file: E('social/slidein-github-org-500.png') });
await onGround(svgs['primary/color'], { w: 1200, h: 630, bg: IV, frac: 0.56, file: E('social/slidein-og-1200x630.png') });
await onGround(svgs['symbol/color'], { size: 1024, bg: IV, frac: 0.60, file: E('application/slidein-app-icon-1024.png') });    // full-bleed: the OS applies its own mask
await onGround(svgs['symbol/reversed'], { size: 1024, bg: BK, frac: 0.60, file: E('application/slidein-app-icon-dark-1024.png') });

// ── 4. PDF: true vector (Chromium prints inline SVG as paths, not bitmaps) ───────────────────────────
const b = await chromium.launch(); const pg = await b.newPage();
for (const [lid, L] of Object.entries(LAYOUTS)) for (const way of ['color', 'black', 'reversed']) {
  const svg = svgs[`${lid}/${way}`], [sw, sh] = dims(svg), k = 288 / sw;       // 288 pt wide; vector, so the size is nominal
  const wpt = Math.round(sw * k), hpt = Math.round(sh * k);
  await pg.setContent(`<style>@page{size:${wpt}pt ${hpt}pt;margin:0}html,body{margin:0;background:${way === 'reversed' ? '#0A0A0A' : 'transparent'}}svg{display:block;width:${wpt}pt;height:${hpt}pt}</style>${svg}`);
  w(E(`print/${L.name}${WAYS[way]}.pdf`), await pg.pdf({ width: `${(wpt / 72).toFixed(4)}in`, height: `${(hpt / 72).toFixed(4)}in`, printBackground: true, pageRanges: '1' }));
}
await b.close();
w(root + 'source/logo-metrics.json', JSON.stringify({ stopSide_x_fraction_of_symbol: +STOP.toFixed(4), gap_in_x: 1.25, layouts: metrics }, null, 2) + '\n');
console.log('logo system built:', Object.keys(svgs).length, 'SVGs');
console.table(metrics);
